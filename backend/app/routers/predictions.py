import logging
from typing import List, Optional, Dict, Any
from datetime import datetime
from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.models.staff import Staff
from app.auth.dependencies import require_roles
from app.services.prediction_service import PredictionService

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/predictions", tags=["Predictive Analytics & Forecasting"])


# ─── Schemas ────────────────────────────────────────────────────────────────

class PredictionRecordRequest(BaseModel):
    model_name: str = Field(..., example="SurgeForecaster_v1")
    model_version: str = Field(default="1.0.0")
    prediction_type: str = Field(..., example="SURGE_FORECAST")  # SURGE_FORECAST, ICU_BED_DEMAND, LENGTH_OF_STAY, MORTALITY_RISK
    input_features: Dict[str, Any] = Field(default_factory=dict)
    prediction_output: Dict[str, Any] = Field(default_factory=dict)
    confidence_score: float = Field(..., ge=0.0, le=1.0, example=0.89)
    inference_time_ms: float = Field(..., example=12.4)
    target_date: Optional[datetime] = None


class PredictionResponse(BaseModel):
    id: str
    model_name: str
    model_version: str
    prediction_type: str
    input_features: Dict[str, Any]
    prediction_output: Dict[str, Any]
    confidence_score: float
    inference_time_ms: float
    target_date: Optional[datetime]
    created_at: datetime

    class Config:
        from_attributes = True


# ─── Endpoints ──────────────────────────────────────────────────────────────

@router.get("/latest", response_model=List[PredictionResponse])
async def get_latest_predictions(
    prediction_type: Optional[str] = Query(None, description="SURGE_FORECAST, ICU_BED_DEMAND, LENGTH_OF_STAY"),
    limit: int = Query(5, ge=1, le=50),
    db: AsyncSession = Depends(get_db)
):
    """Retrieve the most recent predictive model runs for real-time dashboard visualization."""
    service = PredictionService(db)
    return await service.get_latest_predictions(prediction_type=prediction_type, limit=limit)


@router.get("/history", response_model=List[PredictionResponse])
async def list_prediction_history(
    model_name: Optional[str] = Query(None),
    prediction_type: Optional[str] = Query(None),
    limit: int = Query(50, ge=1, le=200),
    db: AsyncSession = Depends(get_db)
):
    """Query historical predictions generated by the analytical engine."""
    service = PredictionService(db)
    return await service.list_prediction_history(
        model_name=model_name,
        prediction_type=prediction_type,
        limit=limit
    )


@router.post("/record", response_model=PredictionResponse, status_code=201)
async def record_prediction_run(
    req: PredictionRecordRequest,
    current_staff: Staff = Depends(require_roles(["ADMINISTRATOR", "DOCTOR", "TECHNICIAN"])),
    db: AsyncSession = Depends(get_db)
):
    """
    Persist an inference result from the Prediction Engine or AI agents.
    Logs inference metrics and confidence scores to the database with RBAC.
    """
    service = PredictionService(db)
    return await service.record_prediction_run(
        model_name=req.model_name,
        model_version=req.model_version,
        prediction_type=req.prediction_type,
        input_features=req.input_features,
        prediction_output=req.prediction_output,
        confidence_score=req.confidence_score,
        inference_time_ms=req.inference_time_ms,
        target_date=req.target_date,
        actor_id=current_staff.id
    )


@router.get("/metrics")
async def get_prediction_metrics(db: AsyncSession = Depends(get_db)):
    """Summary statistics for prediction models (average confidence, inference latency, total runs)."""
    service = PredictionService(db)
    return await service.get_prediction_metrics()
